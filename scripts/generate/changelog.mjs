// Builds the changelog page and each component's history from the
// hand-written entries in frontend-foundation's changelog/ folder (copied to
// foundation/changelog by scripts/foundation/sync.mjs). Only what has an
// entry file is published.

import fs from 'node:fs';
import path from 'node:path';
import { parse as parseYaml } from 'yaml';
import { CONTENT, FOUNDATION, GENERATED } from './paths.mjs';
import { writeIfChanged } from './write.mjs';

const ENTRIES = path.join(FOUNDATION, 'changelog');
const FILE_NAME = /^(\d{4}-\d{2}-\d{2})-[a-z0-9-]+\.md$/;
export const ENTRY_TYPES = ['feature', 'improvement', 'fix', 'breaking'];

function parseEntry(file, slugs) {
    const name = path.basename(file);
    const date = FILE_NAME.exec(name)?.[1];
    if (!date)
        throw new Error(`changelog/${name}: name it YYYY-MM-DD-<slug>.md`);
    const text = fs.readFileSync(file, 'utf8');
    const match = text.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
    if (!match) throw new Error(`changelog/${name}: missing front matter`);
    const data = parseYaml(match[1]) ?? {};
    const title = typeof data.title === 'string' ? data.title.trim() : '';
    const type = data.type;
    const components = data.components ?? [];
    if (
        !Array.isArray(components) ||
        !components.every((c) => typeof c === 'string')
    )
        throw new Error(
            `changelog/${name}: components must be a list of slugs`,
        );
    if (!title) throw new Error(`changelog/${name}: needs a title`);
    if (!ENTRY_TYPES.includes(type))
        throw new Error(
            `changelog/${name}: type must be one of ${ENTRY_TYPES.join(', ')}`,
        );
    const unknown = components.filter((slug) => !slugs.has(slug));
    if (unknown.length)
        throw new Error(
            `changelog/${name}: unknown component slug(s): ${unknown.join(', ')}`,
        );
    return {
        id: name.slice(0, -3),
        date,
        title,
        type,
        components,
        body: match[2].trim(),
    };
}

/**
 * Reads every entry, newest first, checking components against `slugs` (the
 * docs page slugs). `byComponent` maps a slug to the entries that list it.
 */
export function readChangelog(slugs) {
    const files = fs.existsSync(ENTRIES)
        ? fs
              .readdirSync(ENTRIES)
              .filter((f) => f.endsWith('.md') && f !== 'README.md')
        : [];
    if (!files.length)
        console.warn('No frontend-foundation changelog entries found.');
    const entries = files
        .map((f) => parseEntry(path.join(ENTRIES, f), slugs))
        .sort((a, b) => b.id.localeCompare(a.id));
    const byComponent = new Map();
    for (const entry of entries) {
        for (const slug of entry.components)
            byComponent.set(slug, [...(byComponent.get(slug) ?? []), entry]);
    }
    return { entries, byComponent };
}

export const ENTRY_IMPORT =
    "import ChangelogEntry from '@/features/changelog/components/ChangelogEntry';";

/** One entry as MDX; `current` is the component page it's shown on, if any. */
export function entryMdx(entry, current) {
    const props = [
        `type="${entry.type}"`,
        `date="${entry.date}"`,
        `title={${JSON.stringify(entry.title)}}`,
        `components={${JSON.stringify(entry.components)}}`,
        ...(current ? [`current="${current}"`] : []),
    ].join(' ');
    return entry.body
        ? `<ChangelogEntry ${props}>\n\n${entry.body}\n\n</ChangelogEntry>`
        : `<ChangelogEntry ${props} />`;
}

const monthTitle = (date) =>
    new Date(`${date.slice(0, 7)}-01T00:00:00Z`).toLocaleDateString('en-US', {
        month: 'long',
        year: 'numeric',
        timeZone: 'UTC',
    });

function page(entries) {
    const months = new Map();
    for (const entry of entries) {
        const title = monthTitle(entry.date);
        months.set(title, [...(months.get(title) ?? []), entry]);
    }
    const body = months.size
        ? [...months]
              .map(
                  ([title, list]) =>
                      `## ${title}\n\n${list.map((e) => entryMdx(e)).join('\n\n')}`,
              )
              .join('\n\n')
        : 'No changes have been published yet.';
    return `---
title: Changelog
description: New components, improvements and fixes in Frontend Foundation, newest first.
---

{/* Generated by scripts/generate/changelog.mjs from frontend-foundation's changelog/ folder - do not edit. */}

${ENTRY_IMPORT}

${body}
`;
}

/**
 * Writes content/docs/changelog.mdx and the component titles and categories
 * that entries link to (src/generated/changelog-components.json).
 */
export function writeChangelog({ entries }, components) {
    const index = Object.fromEntries(
        components.map((c) => [
            c.slug,
            { title: c.title, category: c.category },
        ]),
    );
    writeIfChanged(
        path.join(GENERATED, 'changelog-components.json'),
        `${JSON.stringify(index, null, 2)}\n`,
    );
    writeIfChanged(path.join(CONTENT, 'changelog.mdx'), page(entries));
}
